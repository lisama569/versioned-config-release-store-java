-- 确定性建表脚本（Spring Boot 启动时执行，幂等）。
-- Hibernate ddl-auto=none，列名遵循 Spring 物理命名策略（驼峰 -> 下划线）。

CREATE TABLE IF NOT EXISTS config_entry (
    seq                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key         VARCHAR(200)  NOT NULL,
    config_value       VARCHAR(4000) NOT NULL,
    description        VARCHAR(1000),
    category           VARCHAR(100) DEFAULT 'DEFAULT',
    status             VARCHAR(20)   NOT NULL,
    value_version      BIGINT        NOT NULL,
    -- 历史行（v1 时代写入）没有新字段，format_version 由默认值补为 1
    format_version     INTEGER       NOT NULL DEFAULT 1,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    optimistic_version BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_entry_key UNIQUE (config_key)
);
CREATE INDEX IF NOT EXISTS idx_entry_created ON config_entry (created_at, seq);

CREATE TABLE IF NOT EXISTS config_revision (
    seq          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_seq    BIGINT        NOT NULL,
    entry_key    VARCHAR(200)  NOT NULL,
    change_type  VARCHAR(20)   NOT NULL,
    version_from BIGINT        NOT NULL,
    version_to   BIGINT        NOT NULL,
    old_value    VARCHAR(4000),
    new_value    VARCHAR(4000),
    operator     VARCHAR(100),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_revision_entry ON config_revision (entry_seq, seq);
CREATE INDEX IF NOT EXISTS idx_revision_created ON config_revision (created_at, seq);

CREATE TABLE IF NOT EXISTS release_order (
    seq                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id         VARCHAR(100) NOT NULL,
    state              VARCHAR(20)  NOT NULL,
    remark             VARCHAR(500),
    format_version     INTEGER      NOT NULL DEFAULT 1,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at       TIMESTAMP WITH TIME ZONE,
    rolled_back_at     TIMESTAMP WITH TIME ZONE,
    -- 生效时间窗（本轮新增）：历史发布单四列全为 NULL，语义上等价于"无时间窗、永不自动回滚"
    effective_at       TIMESTAMP WITH TIME ZONE,
    expire_at          TIMESTAMP WITH TIME ZONE,
    ttl_seconds        BIGINT,
    rollback_trigger   VARCHAR(20),
    optimistic_version BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_release_request UNIQUE (request_id)
);
CREATE INDEX IF NOT EXISTS idx_release_created ON release_order (created_at, seq);
-- 到期扫描：只索引"已发布、尚未回滚且声明了绝对到期时刻"的在途发布单
CREATE INDEX IF NOT EXISTS idx_release_due ON release_order (expire_at, seq);
-- 生效扫描：只索引"已提交、尚未发布且声明了生效时刻"的在途发布单
CREATE INDEX IF NOT EXISTS idx_release_effective ON release_order (effective_at, seq);

-- ---------------------------------------------------------------------------
-- 升级说明：CREATE TABLE IF NOT EXISTS 不会为"已存在的旧文件库"补列。
-- 从无时间窗版本升级、且复用历史 ./data/configstore 文件库时，请先执行一次
-- （列已存在则 H2 会报错，忽略该错误即可；全新库无需执行）：
--
-- ALTER TABLE release_order ADD COLUMN effective_at     TIMESTAMP WITH TIME ZONE;
-- ALTER TABLE release_order ADD COLUMN expire_at        TIMESTAMP WITH TIME ZONE;
-- ALTER TABLE release_order ADD COLUMN ttl_seconds      BIGINT;
-- ALTER TABLE release_order ADD COLUMN rollback_trigger VARCHAR(20);
-- CREATE INDEX IF NOT EXISTS idx_release_due        ON release_order (expire_at, seq);
-- CREATE INDEX IF NOT EXISTS idx_release_effective  ON release_order (effective_at, seq);
--
-- 历史行四列均为 NULL，语义为"无时间窗、永不自动回滚"，回滚行 NULL trigger 读为 MANUAL。
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS release_item (
    seq                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_seq               BIGINT        NOT NULL,
    entry_key                 VARCHAR(200)  NOT NULL,
    value_at_create           VARCHAR(4000),
    value_version_at_create   BIGINT        NOT NULL,
    value_version_at_publish  BIGINT
);
CREATE INDEX IF NOT EXISTS idx_release_item_release ON release_item (release_seq);
